const fs = require('node:fs');
const path = require('node:path');
const withBrowser = require('./browser_cdp.cjs');
const base = process.env.AUTOMATION_UI_URL;
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(base || '')) throw new Error('Use the loopback browser fixture');
withBrowser(async send => {
  const run = async code => { const result = await send('Runtime.evaluate', { expression: code, awaitPromise: true, returnByValue: true }); if (result.exceptionDetails) throw new Error(result.exceptionDetails.exception?.description || result.exceptionDetails.text); return result.result.value; };
  const wait = condition => run(`(async()=>{for(let i=0;i<400;i++){if(${condition})return true;await new Promise(r=>setTimeout(r,50));}throw new Error('Page did not settle: '+document.body.innerText.slice(-1200));})()`);
  const image = async name => { if (!process.env.AUTOMATION_BROWSER_EVIDENCE_DIR) return; fs.mkdirSync(process.env.AUTOMATION_BROWSER_EVIDENCE_DIR, { recursive: true }); const result = await send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: false }); fs.writeFileSync(path.join(process.env.AUTOMATION_BROWSER_EVIDENCE_DIR, name), Buffer.from(result.data, 'base64')); };
  await send('Page.enable');
  await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1050, deviceScaleFactor: 1, mobile: false });
  await send('Page.navigate', { url: base + '/automations' });
  await wait('document.querySelector("[data-create-automation]")');
  await run('document.querySelector("[data-create-automation]").click()');
  await wait('document.querySelector("[data-edit-dialog]").open');
  await run(`(()=>{for(const selector of ['[data-week-field]','[data-once-field]'])if(getComputedStyle(document.querySelector(selector)).display!=='none')throw new Error('Daily schedule must hide weekly and one-time fields');})()`);
  await run(`(()=>{const f=document.querySelector('[data-auto-form]');f.elements.name.value='Bản tin nghiên cứu';f.elements.instruction.value='Tổng hợp dữ liệu fixture và tạo báo cáo.';document.querySelector('[data-review-automation]').click();})()`);
  await wait('!document.querySelector("[data-save-automation]").hidden');
  await image('automations-draft-desktop.png');
  await run('document.querySelector("[data-save-automation]").click()');
  await wait('document.querySelector("[data-run-now]")');
  await run('document.querySelector("[data-run-now]").click()');
  await wait('new URL(location.href).searchParams.get("run")');
  const identities = await run('Object.fromEntries(new URL(location.href).searchParams)');
  await send('Page.navigate', { url: 'about:blank' });
  let completed = false;
  for (let i = 0; i < 100; i++) { const row = await (await fetch(base + '/api/automations/runs/' + identities.run)).json(); if (row.status === 'succeeded') { completed = true; break; } await new Promise(r => setTimeout(r, 100)); }
  if (!completed) throw new Error('Closing the page must not cancel the background run');
  await send('Page.navigate', { url: base + '/automations?automation=' + identities.automation + '&run=' + identities.run });
  await wait('document.body.innerText.includes("30.000 token") && document.body.innerText.includes("Hoàn tất")');
  await run(`(()=>{if(document.querySelector('[data-run-progress]').textContent.trim())throw new Error('Completed answer must not be duplicated as live progress');})()`);
  await image('automations-result-desktop.png');
  await run('document.querySelector("[data-toggle-schedule]").click()');
  await wait('document.querySelector("[data-toggle-schedule]").textContent === "Tắt lịch"');
  await run('document.querySelector("[data-automation-detail] .automation-heading button").click()');
  await wait('document.querySelector("[data-edit-dialog]").open');
  await run(`(()=>{const input=document.querySelector('[name="instruction"]');input.value='SLOW fixture, chờ người dùng dừng';input.dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('[data-review-automation]').click();})()`);
  await wait('!document.querySelector("[data-save-automation]").hidden');
  await run('document.querySelector("[data-save-automation]").click()');
  await wait('!document.querySelector("[data-edit-dialog]").open');
  await run('document.querySelector("[data-run-now]").click()');
  await wait('document.querySelector("[data-run-now]").disabled && document.body.innerText.includes("Đang chạy")');
  await run('document.querySelector("[data-toggle-schedule]").click()');
  await wait('document.querySelector("[data-pause-dialog]").open');
  await image('automations-pause-desktop.png');
  await run('document.querySelector("[data-pause-keep]").click()');
  await wait('document.querySelector("[data-toggle-schedule]").textContent === "Bật lịch"');
  await run('document.querySelector("[data-stop-run]").click()');
  await wait('document.querySelector("[data-close-unknown]")');
  await run('window.confirm=()=>true;document.querySelector("[data-close-unknown]").click()');
  await wait('!document.querySelector("[data-close-unknown]")');
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await wait('document.querySelector(".workspace-shell").classList.contains("sidebar-collapsed")');
  await run(`(()=>{if(document.documentElement.scrollWidth > innerWidth + 1)throw new Error('Mobile page overflows horizontally');})()`);
  await image('automations-mobile.png');
  await send('Page.navigate', { url: base + '/inbox' });
  await wait('document.querySelector(".automation-notice.unread")');
  await image('automations-inbox-mobile.png');
  const before = await run('document.querySelectorAll(".automation-notice.unread").length');
  await run('document.querySelector(".automation-notice.unread button").click()');
  await wait('document.querySelectorAll(".automation-notice.unread").length < ' + before);
  console.log('PASS: real HTTP app/DB/worker, closed page, reload, two pause choices, stop/unknown, inbox and mobile');
}).catch(error => { console.error(error); process.exitCode = 1; });
